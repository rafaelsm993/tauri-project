function ornamentPixels(rows: readonly string[], tier: number): readonly string[] {
  if (tier === 1) return rows;
  const grid = rows.map((row) => [...row]);
  const n = rows.length;
  const mid = n / 2;
  const stamp = (x: number, y: number, pattern: string[]) => {
    pattern.forEach((row, dy) =>
      [...row].forEach((cell, dx) => {
        if (cell !== ".") grid[y + dy][x + dx] = cell;
      }),
    );
  };
  if (tier === 2) {
    stamp(2, 2, ["ggas", "as..", "s..."]);
    stamp(n - 6, 2, ["sagg", "..sa", "...s"]);
    stamp(2, n - 5, ["s...", "as..", "ggas"]);
    stamp(n - 6, n - 5, ["...s", "..sa", "sagg"]);
  } else if (tier === 3) {
    for (let y = 7; y < n - 6; y += 3) {
      stamp(1, y, [".a", "gs", ".s"]);
      stamp(n - 3, y, ["a.", "sg", "s."]);
    }
    stamp(mid - 1, 1, [".g.", "gag", ".s."]);
    stamp(mid - 1, n - 4, [".a.", "gag", ".s."]);
  } else if (tier === 4) {
    for (let y = 4; y < n - 5; y++) {
      const x = y < 7 || y > n - 9 ? 2 : 1;
      stamp(x, y, [y % 4 === 0 ? "g" : "a"]);
      stamp(n - x - 1, y, [y % 4 === 0 ? "a" : "s"]);
    }
    stamp(4, 2, ["ggas"]);
    stamp(n - 8, 2, ["sagg"]);
    stamp(mid - 4, n - 4, ["saggggas", "..asba.."]);
  } else {
    stamp(mid - 6, 1, ["g.....g.....g", "as...gag...sa", "asb..sas..bsa", "saaaagagaaaas"]);
    stamp(1, mid - 3, ["a.s", "ga.", "ag.", "sa.", ".s."]);
    stamp(n - 4, mid - 3, ["s.a", ".ag", ".ga", ".as", ".s."]);
    stamp(mid - 6, n - 4, ["saaaagagaaaas", ".s...asa...s.", "......g......"]);
  }
  return grid.map((row) => row.join(""));
}

export const PROFILE_ART = completionAchievements([], 0).map(
  ({ id, type, name, tier, required, level }) => ({
    id,
    type,
    name,
    tier,
    required,
    level,
    pixels: {
      24: ornamentPixels(PIXELS[type][24], tier),
      32: ornamentPixels(PIXELS[type][32], tier),
    },
  }),
);

export const BASE_PROFILE_ART = PROFILE_ART.filter((art) => art.tier === 1);

const TONES = [
  ["o", "outline"],
  ["s", "shade"],
  ["b", "body"],
  ["a", "accent"],
  ["g", "glint"],
] as const;

function pathsFor(rows: readonly string[]) {
  return TONES.map(([cell, tone]) => ({
    tone,
    d: rows
      .flatMap((row, y) => [...row].map((pixel, x) => (pixel === cell ? `M${x} ${y}h1v1h-1z` : "")))
      .join(""),
  }));
}

const PATHS = new Map(
  PROFILE_ART.map((art) => [
    art.id,
    { 24: pathsFor(art.pixels[24]), 32: pathsFor(art.pixels[32]) },
  ]),
);

export function artworkPaths(id: string, size: 24 | 32) {
  return PATHS.get(id)?.[size] ?? [];
}
